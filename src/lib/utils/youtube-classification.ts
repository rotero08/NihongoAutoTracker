/**
 * ── YouTube Language & Music Rules ───────────────────────────────────────────
 *
 * Decides whether a video is Japanese listening material, whether it is a
 * music video, and whether it was subtitled for a foreign audience. Pure functions over `VideoFacts`, so the rules can be reasoned
 * about (and exercised) without a page.
 */

import type { YouTubePlayerSnapshot } from '@/lib/utils/youtube-player-response';

export type SpokenLanguage = 'japanese' | 'other' | 'unknown';

/** Everything the language / music rules look at, from whichever source could be trusted. */
export interface VideoFacts {
  title: string;
  author: string;
  description: string;
  /** Uploader tags, space separated. */
  keywords: string;
  category: string;
  isLiveNow: boolean;
  spokenLanguage: SpokenLanguage;
  /** Titles of the songs YouTube credits in the description's "Music" card. */
  songs: string[];
  /** Languages of the caption tracks the uploader provided (auto-generated ones excluded). */
  uploadedCaptionLanguages: string[];
}

const MUSIC_CATEGORY = 'Music';

/* ── Language ─────────────────────────────────────────────────────────────── */

/** Hiragana and katakana letters: the only script that is unmistakably Japanese. */
const KANA_RE = /[ぁ-ゖァ-ヺ]/g;
/** Han characters, shared with Chinese. */
const KANJI_RE = /[一-鿿]/g;

const count = (text: string, pattern: RegExp): number => (text ? (text.match(pattern) ?? []).length : 0);
const matchesAny = (patterns: RegExp[], text: string) => patterns.some((pattern) => pattern.test(text));

function isJapaneseLanguageCode(code: string): boolean {
  const lang = code.toLowerCase();
  return lang === 'ja' || lang.startsWith('ja-');
}

/**
 * The language YouTube itself attributes to the audio, when it exposes one.
 *
 * The auto-generated caption track is produced from the audio, so its language
 * is the spoken language. Uploaded caption tracks say nothing on their own: a
 * Japanese track on a foreign video is a translation.
 */
export function getSpokenLanguage(
  snapshot: Pick<YouTubePlayerSnapshot, 'captionTracks' | 'defaultAudioLanguage'>,
): SpokenLanguage {
  // Some videos carry several auto-generated tracks (one per language YouTube
  // heard); Japanese among them is enough.
  const autoGenerated = snapshot.captionTracks.filter((track) => track.kind === 'asr' && track.languageCode);
  if (autoGenerated.length > 0) {
    return autoGenerated.some((track) => isJapaneseLanguageCode(track.languageCode)) ? 'japanese' : 'other';
  }
  if (snapshot.defaultAudioLanguage) {
    return isJapaneseLanguageCode(snapshot.defaultAudioLanguage) ? 'japanese' : 'other';
  }
  const tracks = snapshot.captionTracks;
  if (tracks.length === 1 && isJapaneseLanguageCode(tracks[0].languageCode)) return 'japanese';
  return 'unknown';
}

export function isJapaneseContent(facts: VideoFacts): boolean {
  if (facts.spokenLanguage !== 'unknown') return facts.spokenLanguage === 'japanese';

  // No audio-language signal (typically music, or an upload too recent to have
  // auto-captions): fall back to the script the uploader writes in. Kana is
  // required somewhere, because kanji alone is just as likely to be Chinese —
  // or a single decorative character in an otherwise foreign channel name.
  if (count(facts.title, KANA_RE) >= 1) return true;

  const description = facts.description.slice(0, 1000);
  const authorKana = count(facts.author, KANA_RE);
  const supportingKana = count(description, KANA_RE) + count(facts.keywords, KANA_RE);

  if (count(facts.title, KANJI_RE) >= 2) {
    if (authorKana + supportingKana >= 1) return true;
    // A kanji-only title with nothing else to read is given the benefit of the doubt.
    return description.trim().length < 40 && !facts.keywords.trim();
  }

  return authorKana >= 2
    || supportingKana >= 5
    || (count(facts.author, KANJI_RE) >= 2 && supportingKana >= 1);
}

/* ── Subtitled for a foreign audience ─────────────────────────────────────── */

const SUB_LANGUAGES = 'eng(?:lish)?|en|esp(?:a[ñn]ol)?|es|spanish|indo(?:nesian?)?|id|pt-?br|portugu[eê]se?|fr(?:ench)?|german|deutsch|ita(?:lian[o]?)?|ru(?:ssian)?|kor(?:ean)?|chinese|thai|viet(?:namese)?|multi';
const SUB_WORDS = 'sub(?:s|bed|title[sd]?|titulado|t[ií]tulos)?|cc';

/** "EN Sub", "English subtitles", "Sub-Español", "[ENG]", 英語字幕 … */
const FOREIGN_SUB_PATTERNS = [
  new RegExp(`\\b(?:${SUB_LANGUAGES})[\\s\\-_/]*(?:${SUB_WORDS})\\b`, 'i'),
  new RegExp(`\\b(?:${SUB_WORDS})[\\s\\-_/]*(?:${SUB_LANGUAGES})\\b`, 'i'),
  /[[【(（]\s*(?:eng|english|esp|español|indo|中字)\s*[\]】)）]/i,
  /英語字幕|中文字幕|한글\s*자막|subtitulado|legendado|sous-titr|с субтитрами/i,
];

/** Fan-translation channels and uploads name themselves this way. */
const CLIP_PATTERNS = [
  /\bclip(?:s|per|pers|ped)?\b/i,
  /\bvtuber\s?clips?\b/i,
  /\b(?:subs|subbed|translat(?:ed|ions?|or))\b/i,
];

/** A description line crediting the stream a clip was cut from: "Source:", "[Sources]", "Original Stream". */
const SOURCE_CREDIT_RE = /^[^\p{L}\p{N}\n]*(?:sources?|original (?:stream|video|vod)s?|source (?:stream|video)s?)\s*(?:[\]】)]\s*)?(?:[:：]|$)/imu;

const LATIN_LETTER_RE = /[A-Za-z\u00c0-\u024f]/g;

/** The title is written for people who do not read Japanese. */
function hasForeignTitle(title: string): boolean {
  const japanese = count(title, KANA_RE) + count(title, KANJI_RE);
  const latin = count(title, LATIN_LETTER_RE);
  return latin >= 10 && japanese * 3 <= latin;
}

/**
 * Whether a Japanese-audio video carries subtitles in another language — the
 * fan-translated clip, mostly. Reading along in another language is not
 * listening practice, so these are kept out of the log unless the user opts in.
 *
 * Deliberately conservative: a foreign title alone proves nothing (plenty of
 * learner podcasts have one), so it must come with a second sign that the
 * upload is a translation. When in doubt the video counts as plain Japanese.
 */
export function isForeignSubtitledContent(facts: VideoFacts): boolean {
  if (matchesAny(FOREIGN_SUB_PATTERNS, facts.title)) return true;
  if (!hasForeignTitle(facts.title)) return false;

  const description = facts.description.slice(0, 1500);
  if (matchesAny(FOREIGN_SUB_PATTERNS, facts.keywords) || matchesAny(FOREIGN_SUB_PATTERNS, description.slice(0, 400))) {
    return true;
  }
  if (matchesAny(CLIP_PATTERNS, `${facts.title}\n${facts.author}\n${facts.keywords}`)) return true;
  if (SOURCE_CREDIT_RE.test(description)) return true;

  // Captions uploaded in other languages but not in Japanese: a translation, not a transcript.
  const uploaded = facts.uploadedCaptionLanguages;
  return uploaded.length > 0 && !uploaded.some(isJapaneseLanguageCode);
}

/* ── Music ────────────────────────────────────────────────────────────────── */

/** Titles that announce an official release. */
const RELEASE_TITLE_PATTERNS = [
  /\b(official music video|music video|lyrics? video|official mv|official audio|official video|official visualizer)\b/i,
  /【mv】|\[mv\]/i,
  /\bm\/?v\b/i,
  /(ノンクレジット|アニメ)?(op|ed)(映像|ムービー)/i,
];

/** Titles of covers, karaoke tracks, lyric videos and other fan-made music uploads. */
const SONG_TITLE_PATTERNS = [
  /[([【（「]\s*(lyrics?|歌詞|和訳|日本語訳)[^)\]】）」]*[)\]】）」]/i,
  /\b(with lyrics|lyrics?\s*$)/i,
  /歌詞(付き|つき|あり|入り|動画)|歌ってみた|弾いてみた|叩いてみた|演奏してみた/,
  // Bare カラオケ / インスト also name karaoke vlogs and "install" (インストール).
  /ニコカラ|[【[(（]\s*カラオケ[^】\])）]*[】\])）]|カラオケ(音源|字幕|ver)/i,
  /オフボーカル|オンボーカル|インスト(ゥルメンタル)?(?![ァ-ヶー])/,
  /\b(off ?vocal|on ?vocal|instrumental|nightcore|full album|original soundtrack)\b/i,
  /\bcover(ed)? by\b|[【[(（]\s*cover\s*[】\])）]|\bcover\s*$/i,
  /オリジナル(曲|楽曲|ソング)|\boriginal song\b/i,
  /\bTHE FIRST TAKE\b/,
];

/** Channels that only publish music. */
const MUSIC_AUTHOR_RE = /( - Topic|VEVO)$/;

/** Live streams that present themselves as background music rather than talk. */
const LIVE_MUSIC_TITLE_RE = /\b(24\/7|radio|lo-?fi|bgm|playlist)\b|作業用|睡眠用|勉強用/i;

/** Letters and digits only, width- and case-folded, so punctuation variants compare equal. */
function normalizeForMatch(text: string): string {
  return text.normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
}

/**
 * Whether the video is named after one of the songs YouTube credits it with.
 * The credit alone is not enough — any vlog with background music has one.
 */
function isNamedAfterCreditedSong(facts: VideoFacts): boolean {
  const title = normalizeForMatch(facts.title);
  return facts.songs.some((song) => {
    const name = normalizeForMatch(song);
    // Very short Latin names ("OK", "Go") turn up inside unrelated words.
    const minLength = /^[\x20-\x7e]+$/.test(name) ? 4 : 2;
    return name.length >= minLength && title.includes(name);
  });
}

export function isMusicContent(facts: VideoFacts): boolean {
  const isRelease = matchesAny(RELEASE_TITLE_PATTERNS, facts.title);

  if (facts.isLiveNow) {
    // A live stream filed under "Music" is usually a talk or karaoke stream.
    // It only counts as music when it also presents itself as a music feed.
    return facts.category === MUSIC_CATEGORY && (isRelease || LIVE_MUSIC_TITLE_RE.test(facts.title));
  }

  if (facts.category === MUSIC_CATEGORY || isRelease) return true;
  if (matchesAny(SONG_TITLE_PATTERNS, facts.title) || MUSIC_AUTHOR_RE.test(facts.author)) return true;
  if (isNamedAfterCreditedSong(facts)) return true;

  // Art tracks distributed by labels
  return facts.description.includes('Auto-generated by YouTube') || facts.description.includes('Provided to YouTube');
}
